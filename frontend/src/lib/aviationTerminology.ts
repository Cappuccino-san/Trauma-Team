export function formatLimitingFactorLabel(code?: string | null): string {
  if (!code) return 'NONE — ALL MARGINS NOMINAL';
  const normalized = code.trim().toUpperCase();
  if (LIMITING_FACTOR_CALLOUTS[normalized]) {
    return LIMITING_FACTOR_CALLOUTS[normalized];
  }
  return normalized.replace(/_/g, ' ');
}

export function isWeatherOrAirspaceLimitingFactor(code?: string | null): boolean {
  if (!code) return false;
  return WEATHER_AIRSPACE_FACTORS.has(code.trim().toUpperCase());
}

export function formatTelemetryModeLabel(state: ConnectionState): string {
  switch (state) {
    case 'CONNECTED':
      return 'LIVE FEED';
    case 'STATIC_SIM':
      return 'STATIC SIM';
    case 'CONNECTING':
      return 'CONNECTING';
    case 'RECONNECTING':
      return 'RECONNECTING';
    case 'ERROR':
      return 'FEED FAULT';
    default:
      return 'OFFLINE';
  }
}

export function formatZuluClock(date: Date = new Date()): string {
  return `${date.toISOString().slice(11, 16)}Z`;
}
